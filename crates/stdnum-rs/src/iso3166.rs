//! The ISO 3166-1 alpha-2 country codes.
//!
//! Several identifiers embed a country code and have to reject one that was
//! never assigned. The list lives here rather than in each module so the codes
//! cannot drift apart between them. It includes the codes that were withdrawn
//! (`AN`, `CS`) because numbers that carry them are still in circulation.

