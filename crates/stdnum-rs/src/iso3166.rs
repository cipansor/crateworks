/// Whether `code` is an assigned ISO 3166-1 alpha-2 code.
#[must_use]
pub(crate) fn is_assigned(code: &str) -> bool {
    CODES.contains(&code)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_assigned_and_withdrawn_codes() {
        assert!(is_assigned("NL"));
        assert!(is_assigned("US"));
        assert!(!is_assigned("XK"), "Kosovo is user-assigned");
        assert!(is_assigned("AN"), "Netherlands Antilles, withdrawn 2010");
    }

    #[test]
    fn rejects_non_countries() {
        assert!(!is_assigned("ZZ"));
        assert!(!is_assigned("EU"));
        assert!(!is_assigned(""));
        assert!(!is_assigned("N"));
    }
}
