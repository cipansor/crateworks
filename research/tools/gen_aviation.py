#!/usr/bin/env python3
"""Generate the airport table and test fixtures for the aviation-data crate.

    python3 research/tools/gen_aviation.py crates/aviation-data

Source of truth: OurAirports (https://ourairports.com/data/), a public-domain
dataset published by David Megginson. The download is
https://davidmegginson.github.io/ourairports-data/airports.csv.

The generated file keeps the ORIGINAL TEXT of every retained field, so a diff
against the upstream CSV is a set comparison and nothing is lost to
reformatting. Rows are sorted by `ident` so the file stays reviewable.

What is kept: every airport that is not `closed` and that carries an IATA or an
ICAO code. That is the set a lookup can actually address; the remaining 60,000
rows are small private fields, heliports and closed strips with no code, which
would multiply the file size for no lookup value. The count is asserted below so
a silent upstream change fails the generator instead of shrinking the crate.
"""

import csv
import io
import sys
import urllib.request
from pathlib import Path

CSV_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"

# Field order in the generated TSV. `csv_field` is the upstream column name.
FIELDS = [
    ("ident", "ident"),
    ("kind", "type"),
    ("name", "name"),
    ("lat", "latitude_deg"),
    ("lon", "longitude_deg"),
    ("elevation_ft", "elevation_ft"),
    ("continent", "continent"),
    ("country", "iso_country"),
    ("region", "iso_region"),
    ("municipality", "municipality"),
    ("scheduled", "scheduled_service"),
    ("iata", "iata_code"),
    ("icao", "icao_code"),
    ("gps", "gps_code"),
    ("local", "local_code"),
]

KINDS = [
    "large_airport",
    "medium_airport",
    "small_airport",
    "heliport",
    "seaplane_base",
    "balloonport",
]

# The set is pinned so a silent upstream shrink or a changed filter is caught
# here rather than shipped.
#
# OurAirports is maintained continuously, so this number moves on its own: it
# was 11,848 when the crate was first generated and 11,889 on 2026-10-21, the
# difference being a South African cleanup (13 strips dropped, 54 added, 10
# corrected). That is the point of the assertion. It is not a stable constant to
# be relaxed when it fails - a failure means upstream has moved and the table
# has to be regenerated and the change reviewed, because the crate ships a
# snapshot and the gate is a freshness check rather than a reproducibility one.
EXPECTED_ROWS = 11889


def fetch() -> str:
    req = urllib.request.Request(CSV_URL, headers={"User-Agent": "crateworks-gen"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read().decode("utf-8")


def clean(value: str) -> str:
    """Collapse the characters that would break the one-record-per-line TSV.

    Names carry non-ASCII (1,157 of the retained rows) and must survive, so this
    strips control characters only, never transliterates.
    """
    return value.replace("\t", " ").replace("\r", " ").replace("\n", " ").strip()


def build(rows: list[dict[str, str]]) -> list[list[str]]:
    out = []
    for r in rows:
        if clean(r.get("type", "")) == "closed":
            continue
        if not clean(r.get("iata_code", "")) and not clean(r.get("icao_code", "")):
            continue
        kind = clean(r.get("type", ""))
        if kind not in KINDS:
            raise SystemExit(f"unexpected airport type {kind!r} in {r.get('ident')!r}")
        out.append([clean(r.get(csv_field, "")) for _, csv_field in FIELDS])
    out.sort(key=lambda rec: rec[0])
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    crate = Path(sys.argv[1])
    if not crate.is_dir():
        raise SystemExit(f"not a directory: {crate}")

    rows = list(csv.DictReader(io.StringIO(fetch())))
    records = build(rows)
    if len(records) != EXPECTED_ROWS:
        raise SystemExit(
            f"filtered to {len(records)} rows, expected {EXPECTED_ROWS}; "
            "upstream changed - review before updating EXPECTED_ROWS"
        )

    header = (
        "# OurAirports airport reference table.\n"
        "# Generated by research/tools/gen_aviation.py - do not edit by hand.\n"
        "# Source: https://ourairports.com/data/ (public domain, David Megginson).\n"
        f"# {len(records)} rows, one per non-closed airport with an IATA or ICAO code.\n"
        "# Columns: " + ", ".join(name for name, _ in FIELDS) + "\n"
        "# An empty field means the upstream column is empty.\n"
    )
    body = "\n".join("\t".join(rec) for rec in records) + "\n"

    data = crate / "data"
    data.mkdir(exist_ok=True)
    (data / "airports.tsv").write_text(header + body, encoding="utf-8")

    # Fixtures: a spread of lookups the Rust tests assert against, taken from the
    # data rather than written by hand, so the test cannot drift from the table.
    fixtures = ["# ident\tkind\tname\tiata\ticaolat\tlon"]
    by_code: dict[str, list[str]] = {}
    for rec in records:
        for code in (rec[11], rec[12]):
            if code:
                by_code[code] = rec
    # One entry per airport: a code and its ident resolve to the same row, so
    # listing both would only duplicate the record under a second key.
    seen: set[str] = set()
    for code in ["LHR", "JFK", "CGK", "DXB", "HND", "SIN", "AMS", "HKG",
                 "KLAX", "SYD", "CDG", "FRA", "NRT", "DEL", "DOH", "PEK",
                 "ATL", "YYZ", "GRU", "CPT", "AUH", "IST", "MAD", "CAI"]:
        rec = by_code.get(code)
        if rec is None:
            raise SystemExit(f"fixture code {code} not in the table")
        if rec[0] in seen:
            continue
        seen.add(rec[0])
        fixtures.append("\t".join([rec[0], rec[1], rec[2], rec[11], rec[12], rec[3], rec[4]]))
    (crate / "tests" / "fixtures").mkdir(parents=True, exist_ok=True)
    (crate / "tests" / "fixtures" / "lookups.tsv").write_text(
        "\n".join(fixtures) + "\n", encoding="utf-8"
    )

    size = (data / "airports.tsv").stat().st_size
    print(f"{len(records)} rows -> {data / 'airports.tsv'} ({size / 1024:.0f} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
