#!/usr/bin/env python3
"""Regression gate for `crates/fuzzy-score` against the Python `fuzzywuzzy`.

`fuzzywuzzy` 0.18 is the reference this crate ports, so a difference is a bug in
one of the two. This script generates a scratch Rust example, runs the crate's
scoring functions over a large corpus, and compares every number with the
reference. It exits non-zero on any mismatch.

The corpus is drawn from a seeded xorshift generator, so a failure is
reproducible: the same run fails on the same case.

**The oracle must be the pure-Python `difflib.SequenceMatcher`.** When the
`Levenshtein` package (from `python-Levenshtein`) is importable, `fuzzywuzzy`
silently substitutes a `Levenshtein`-backed matcher that returns *different*
ratios - `36` where `difflib` gives `24` on one two-character case. Any
comparison made in that state is meaningless, so the script refuses to run and
tells you to uninstall it.

Run:  python3 research/tools/verify_fuzzy_score.py [--cases N] [--write-fixture]
Needs: pip install fuzzywuzzy==0.18.0   (and NOT python-Levenshtein)
"""

import argparse
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRATE = ROOT / "crates" / "fuzzy-score"
CARGO_ENV = {
    **os.environ,
    "PATH": "/workspace/.toolchain/cargo/bin:" + os.environ.get("PATH", ""),
    "CARGO_HOME": "/workspace/.toolchain/cargo",
}

# The ten functions under test, in fixture column order.
FUNCTIONS = [
    "ratio", "partial_ratio", "token_sort_ratio", "partial_token_sort_ratio",
    "token_set_ratio", "partial_token_set_ratio", "w_ratio", "q_ratio",
    "uw_ratio", "uq_ratio",
]

EXAMPLE = """//! Generated by research/tools/verify_fuzzy_score.py. Do not edit.
use std::io::{self, BufRead, Write};
use fuzzy_score::fuzz;

fn main() {
    let stdin = io::stdin();
    let stdout = io::stdout();
    let mut out = stdout.lock();
    for line in stdin.lock().lines() {
        let line = line.unwrap();
        if line.is_empty() { continue; }
        let mut it = line.splitn(2, '\\t');
        let a = it.next().unwrap_or("");
        let b = it.next().unwrap_or("");
        writeln!(out, "{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}\\t{}",
            fuzz::ratio(a, b),
            fuzz::partial_ratio(a, b),
            fuzz::token_sort_ratio(a, b),
            fuzz::partial_token_sort_ratio(a, b),
            fuzz::token_set_ratio(a, b),
            fuzz::partial_token_set_ratio(a, b),
            fuzz::w_ratio(a, b),
            fuzz::q_ratio(a, b),
            fuzz::uw_ratio(a, b),
            fuzz::uq_ratio(a, b)).unwrap();
    }
}
"""


PROCESS_EXAMPLE = """//! Generated by research/tools/verify_fuzzy_score.py. Do not edit.
use std::io::{self, BufRead, Write};
use fuzzy_score::{Scorer, dedupe, extract, extract_bests, extract_one, extract_without_order};

fn main() {
    let stdin = io::stdin();
    let stdout = io::stdout();
    let mut out = stdout.lock();
    for line in stdin.lock().lines() {
        let line = line.unwrap();
        if line.is_empty() { continue; }
        let mut parts = line.split('\\u{1f}');
        let query = parts.next().unwrap_or("");
        let choices: Vec<&str> = parts.collect();
        let best = extract(query, choices.iter().copied(), Some(5), Scorer::WRatio);
        let bests = extract_bests(query, choices.iter().copied(), 40, Some(5), Scorer::WRatio);
        let one = extract_one(query, choices.iter().copied(), 0, Scorer::WRatio);
        let unordered = extract_without_order(query, choices.iter().copied(), 40, Scorer::WRatio);
        let unique = dedupe(choices.iter().copied(), 70);
        let best = best.iter().map(|(c, s)| format!("{s}:{c}")).collect::<Vec<_>>().join("\\u{1e}");
        let bests = bests.iter().map(|(c, s)| format!("{s}:{c}")).collect::<Vec<_>>().join("\\u{1e}");
        let one = one.map_or_else(|| "-".to_string(), |(c, s)| format!("{s}:{c}"));
        let unordered = unordered.iter().map(|(c, s)| format!("{s}:{c}")).collect::<Vec<_>>().join("\\u{1e}");
        let unique = unique.join("\\u{1e}");
        writeln!(out, "{best}\\t{bests}\\t{one}\\t{unordered}\\t{unique}").unwrap();
    }
}
"""


class Xorshift:
    """The generator the corpus is drawn from, so a failure is reproducible."""

    def __init__(self, seed=0x2545F4914F6CDD1D):
        self.s = seed

    def next(self):
        x = self.s
        x ^= (x << 13) & 0xFFFFFFFFFFFFFFFF
        x ^= x >> 7
        x ^= (x << 17) & 0xFFFFFFFFFFFFFFFF
        self.s = x
        return x

    def below(self, n):
        return self.next() % n


def check_oracle():
    """Refuse to run against a Levenshtein-backed matcher."""
    try:
        import fuzzywuzzy.fuzz as fuzz_module
    except ImportError:
        raise SystemExit("needs: pip install fuzzywuzzy==0.18.0")
    matcher = fuzz_module.SequenceMatcher.__name__
    if matcher != "SequenceMatcher":
        raise SystemExit(
            f"oracle is contaminated: fuzzywuzzy is using {matcher}, not the "
            "pure-Python difflib.SequenceMatcher.\n"
            "Run: pip uninstall -y python-Levenshtein Levenshtein"
        )


def corpus(count):
    """Input pairs: ASCII, a Unicode mix, and long strings for autojunk."""
    rng = Xorshift()
    ascii_pool = list("abc ABC123-_.,!") + ["\t", "\n"]
    uni_pool = (
        list("abcABC 12-_")
        + [chr(c) for c in range(0xC0, 0x100)]
        + [chr(c) for c in range(0x300, 0x310)]
        + ["中", "م", "\u1234", "\u20ac", "\U0001F600", "\u00a0", "\u3000"]
    )

    def make(pool, maxlen):
        return "".join(pool[rng.below(len(pool))] for _ in range(rng.below(maxlen)))

    pairs = []
    for i in range(count):
        pool = ascii_pool if i % 2 == 0 else uni_pool
        pairs.append((make(pool, 28), make(pool, 28)))
    # difflib only applies its popular-element heuristic at 200 elements or
    # more, so short inputs never reach it.
    for _ in range(count // 20):
        a = "".join("abcd"[rng.below(4)] for _ in range(200 + rng.below(200)))
        b = "".join("abcd"[rng.below(4)] for _ in range(200 + rng.below(200)))
        pairs.append((a, b))
    return pairs


def sanitize(s):
    """Strips the characters the process wire format uses as separators.

    Unit separator and newline divide the fields; tab divides the output. None
    of them changes a score, because `full_process` treats them all as
    non-alphanumeric and drops them, so the reference and the crate see the same
    strings and a difference is a real one.
    """
    return (
        s.replace("\u001f", "").replace("\u001e", "").replace("\n", " ").replace("\t", " ")
    )


def process_corpus(count):
    """Queries and choice lists for `process.extract` / `extractOne` / `dedupe`.

    Each entry is `(query, choices)`. The choices mix near-duplicates (so
    `dedupe` has something to collapse) with unrelated strings, drawn from the
    same pools as the scoring corpus so the Unicode paths are exercised too.
    """
    rng = Xorshift(seed=0x9E3779B97F4A7C15)
    ascii_pool = list("abc ABC123-_.,!") + ["\t", "\n"]
    uni_pool = (
        list("abcABC 12-_")
        + [chr(c) for c in range(0xC0, 0x100)]
        + ["中", "م", "\u1234", "\U0001F600", "\u00a0"]
    )
    cases = []
    for i in range(count):
        pool = ascii_pool if i % 2 == 0 else uni_pool
        query = "".join(pool[rng.below(len(pool))] for _ in range(rng.below(20)))
        choices = []
        for _ in range(1 + rng.below(6)):
            if choices and rng.below(3) == 0:
                # A near-duplicate of an earlier choice, so dedupe fires.
                base = choices[rng.below(len(choices))]
                mutation = list(base)
                if mutation and rng.below(2) == 0:
                    mutation[rng.below(len(mutation))] = pool[rng.below(len(pool))]
                else:
                    mutation.append(pool[rng.below(len(pool))])
                choices.append("".join(mutation))
            else:
                choices.append("".join(pool[rng.below(len(pool))] for _ in range(rng.below(20))))
        cases.append((query, choices))
    return cases


def reference_process(cases):
    """The reference's `extract`/`extractBests`/`extractOne`/`dedupe`/`extractWithoutOrder`."""
    from fuzzywuzzy import process
    out = []
    for query, choices in cases:
        best = process.extract(query, choices, limit=5)
        bests = process.extractBests(query, choices, score_cutoff=40, limit=5)
        one = process.extractOne(query, choices)
        # `extractWithoutOrder` is a generator in the reference; it yields in
        # input order and applies the cutoff, so it is the raw material of the
        # other two rather than a ranking.
        unordered = list(process.extractWithoutOrder(query, choices, score_cutoff=40))
        try:
            unique = list(process.dedupe(choices, threshold=70))
            unique_s = "\x1e".join(unique)
        except IndexError:
            # `dedupe` crashes when a choice processes to an empty string: every
            # match scores 0, the filtered list is empty, and the reference
            # indexes into it. There is no reference answer to compare against,
            # so the case is skipped for `dedupe`; the crate must still return a
            # value rather than panicking.
            unique_s = None
        best_s = "\x1e".join(f"{score}:{text}" for text, score in best)
        bests_s = "\x1e".join(f"{score}:{text}" for text, score in bests)
        unordered_s = "\x1e".join(f"{score}:{text}" for text, score in unordered)
        one_s = "-" if one is None else f"{one[1]}:{one[0]}"
        out.append((best_s, bests_s, one_s, unordered_s, unique_s))
    return out


def rust_process(cases, scratch):
    stdin = "".join(
        query + "\x1f" + "\x1f".join(choices) + "\n" for query, choices in cases
    )
    r = subprocess.run(
        ["cargo", "run", "--quiet", "--example", "_oracle_process"],
        cwd=CRATE, input=stdin, capture_output=True, text=True, env=CARGO_ENV,
    )
    if r.returncode != 0:
        raise SystemExit(r.stderr[-3000:])
    # A plain split, not `splitlines`: the record separator is U+001E, which
    # Python also treats as a line boundary, so `splitlines` would shred a row.
    rows = [line.split("\t") for line in r.stdout.split("\n") if line]
    if len(rows) != len(cases):
        raise SystemExit(f"expected {len(cases)} rows, got {len(rows)}")
    return [tuple(row) for row in rows]


def escape(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        elif ord(ch) <= 0xFFFF:
            out.append("\\u%04X" % ord(ch))
        else:
            out.append("\\U%08X" % ord(ch))
    return "".join(out)


def write_example():
    (CRATE / "examples").mkdir(exist_ok=True)
    scratch = CRATE / "examples" / "_oracle_scores.rs"
    scratch.write_text(EXAMPLE)
    return scratch


def rust_scores(pairs, scratch):
    stdin = "".join(
        a.replace("\t", "\x0b").replace("\n", "\x0c")
        + "\t"
        + b.replace("\t", "\x0b").replace("\n", "\x0c")
        + "\n"
        for a, b in pairs
    )
    r = subprocess.run(
        ["cargo", "run", "--quiet", "--example", "_oracle_scores"],
        cwd=CRATE, input=stdin, capture_output=True, text=True, env=CARGO_ENV,
    )
    if r.returncode != 0:
        raise SystemExit(r.stderr[-3000:])
    rows = [line.split("\t") for line in r.stdout.splitlines()]
    if len(rows) != len(pairs):
        raise SystemExit(f"expected {len(pairs)} rows, got {len(rows)}")
    return [[int(x) for x in row] for row in rows]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", type=int, default=2000)
    parser.add_argument("--write-fixture", action="store_true")
    args = parser.parse_args()

    check_oracle()
    from fuzzywuzzy import fuzz

    pairs = corpus(args.cases)
    ref = [
        [fn(a, b) for fn in (
            fuzz.ratio, fuzz.partial_ratio, fuzz.token_sort_ratio,
            fuzz.partial_token_sort_ratio, fuzz.token_set_ratio,
            fuzz.partial_token_set_ratio, fuzz.WRatio, fuzz.QRatio,
            fuzz.UWRatio, fuzz.UQRatio,
        )]
        for a, b in pairs
    ]

    if args.write_fixture:
        path = CRATE / "tests" / "fixtures" / "oracle.tsv"
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w") as f:
            f.write("# fuzzywuzzy 0.18 (pure-python difflib) oracle, generated by\n")
            f.write("# research/tools/verify_fuzzy_score.py --write-fixture\n")
            f.write("# a\tb\t" + "\t".join(FUNCTIONS) + "\n")
            for (a, b), scores in zip(pairs, ref):
                f.write(f"{escape(a)}\t{escape(b)}\t" + "\t".join(map(str, scores)) + "\n")
        print(f"wrote {len(pairs)} cases to {path.relative_to(ROOT)}")

    scratch = write_example()
    try:
        got = rust_scores(pairs, scratch)
    finally:
        scratch.unlink()

    # The `process` functions: extract, extractBests, extractOne,
    # extractWithoutOrder and dedupe. The scorer corpus above only covers
    # `fuzz`; these five are a separate code path with their own ordering and
    # preprocessing rules.
    # The wire format is line and unit-separator based, so the corpus is
    # sanitized once and the reference is asked about the same strings the crate
    # will see.
    cases = [
        (
            sanitize(query),
            [sanitize(c) for c in choices],
        )
        for query, choices in process_corpus(args.cases)
    ]
    ref_process = reference_process(cases)
    scratch = CRATE / "examples" / "_oracle_process.rs"
    scratch.write_text(PROCESS_EXAMPLE)
    try:
        got_process = rust_process(cases, scratch)
    finally:
        scratch.unlink()

    process_names = ["extract", "extractBests", "extractOne", "extractWithoutOrder", "dedupe"]
    process_mismatches = [0] * len(process_names)
    shown_process = 0
    skipped_dedupe = 0
    for (query, choices), expected, actual in zip(cases, ref_process, got_process):
        for k in range(len(process_names)):
            if expected[k] is None:
                # The reference crashed on this case; nothing to compare.
                skipped_dedupe += 1
                continue
            if expected[k] != actual[k]:
                process_mismatches[k] += 1
                if shown_process < 10:
                    shown_process += 1
                    print(
                        f"  {process_names[k]}: expected {expected[k]!r}, got {actual[k]!r}"
                        f"  for {query!r} over {choices!r}"
                    )

    mismatches = [0] * len(FUNCTIONS)
    shown = 0
    for (a, b), expected, actual in zip(pairs, ref, got):
        for k in range(len(FUNCTIONS)):
            if expected[k] != actual[k]:
                mismatches[k] += 1
                if shown < 10:
                    shown += 1
                    print(
                        f"  {FUNCTIONS[k]}: expected {expected[k]}, got {actual[k]}"
                        f"  for {a!r} vs {b!r}"
                    )

    print(f"\ncompared {len(pairs)} pairs x {len(FUNCTIONS)} functions")
    for name, count in zip(FUNCTIONS, mismatches):
        status = "ok" if count == 0 else "BUG"
        print(f"  {status:3s} {name:24s} {count} mismatch(es)")
    print(f"\ncompared {len(cases)} cases x {len(process_names)} process functions")
    for name, count in zip(process_names, process_mismatches):
        status = "ok" if count == 0 else "BUG"
        print(f"  {status:3s} {name:24s} {count} mismatch(es)")
    if skipped_dedupe:
        print(f"  note: {skipped_dedupe} dedupe case(s) skipped, the reference crashes on them")
    total = sum(mismatches) + sum(process_mismatches)
    print(f"\n{total} total mismatch(es)")
    return 1 if total else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except ImportError as e:
        raise SystemExit(f"needs: pip install fuzzywuzzy==0.18.0 ({e})")
