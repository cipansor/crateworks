# A literal is (rust_formula_text, js_value_literal, python_value).
# The same value must be written the two ways each side understands.
def num(v):
    return (repr(v), repr(v), v)


def text(v):
    escaped = v.replace("\\", "\\\\").replace('"', '\\"')
    js = json.dumps(v)
    return (f'"{escaped}"', js, v)


