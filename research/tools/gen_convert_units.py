#!/usr/bin/env python3
"""Generate the unit table for `CONVERT` in `crates/spreadsheet-formula`.

The table is the one `@formulajs/formulajs` carries inside its `CONVERT`
function, extracted from the installed package rather than retyped. Each entry
is `[name, symbol, aliases, category, si, prefixable, factor]`; only the symbol,
the aliases, the category and the factor take part in a conversion, so the other
three columns are dropped.

Every string is emitted with `\\u{...}` escapes for its non-ASCII characters, so
the generated file stays pure ASCII even though the table holds `Å`, `°` and
`Ω`. That keeps the source readable in any editor and diffable.

Usage:
    python3 research/tools/gen_convert_units.py [crate_dir]
Needs: npm install @formulajs/formulajs
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
crate = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "crates" / "spreadsheet-formula")

# The `units` array is a local inside the browser build of the reference. Pull
# it out with the same evaluator the reference itself uses, so the table cannot
# drift from the package that is installed.
EXTRACT = r"""
const fs = require('fs');
const s = fs.readFileSync('node_modules/@formulajs/formulajs/lib/browser/formula.js', 'utf8');
const i = s.indexOf('function CONVERT(');
const j = s.indexOf('var units = [', i);
let depth = 0, k = s.indexOf('[', j);
for (; k < s.length; k++) {
  if (s[k] === '[') depth++;
  else if (s[k] === ']') { depth--; if (depth === 0) break; }
}
process.stdout.write(JSON.stringify(eval(s.slice(s.indexOf('[', j), k + 1))));
"""


def rust_string(text: str) -> str:
    """A Rust string literal, ASCII-only, with non-ASCII characters escaped."""
    out = ['"']
    for ch in text:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):04x}}}")
    out.append('"')
    return "".join(out)


def main() -> int:
    raw = subprocess.run(
        ["node", "-e", EXTRACT], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout
    units = json.loads(raw)

    lines = [
        "// Generated by research/tools/gen_convert_units.py - do not edit by hand.",
        "//",
        "// The unit table of `@formulajs/formulajs`'s `CONVERT`, extracted from the",
        "// installed package. See NOTICE.",
        "",
        "/// One unit `CONVERT` knows: the symbol it is written with, its aliases,",
        "/// the category it belongs to, and its factor to the category's base unit.",
        "pub(crate) struct Unit {",
        "    pub(crate) symbol: &'static str,",
        "    pub(crate) aliases: &'static [&'static str],",
        "    pub(crate) category: &'static str,",
        "    pub(crate) factor: f64,",
        "}",
        "",
        "pub(crate) static UNITS: &[Unit] = &[",
    ]
    for name, symbol, aliases, category, _si, _prefixable, factor in units:
        alias_text = ", ".join(rust_string(a) for a in (aliases or []))
        lines.append("    Unit {")
        lines.append(f"        symbol: {rust_string(symbol)},")
        lines.append(f"        aliases: &[{alias_text}],")
        lines.append(f"        category: {rust_string(category)},")
        # `repr` round-trips a float exactly, which the factor must.
        lines.append(f"        factor: {repr(float(factor))},")
        lines.append("    },")
    lines.append("];")
    lines.append("")

    out = crate / "src" / "convert_table.rs"
    out.write_text("\n".join(lines))
    print(f"wrote {len(units)} units to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
