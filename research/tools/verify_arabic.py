def corpus():
    """Every input the two implementations are compared on."""
    cases = []
    # A letter alone, between two letters, and at each end.
    for letter in LETTERS:
        cases.append(letter)
        cases.append("ب" + letter)
        cases.append(letter + "ب")
        cases.append("ب" + letter + "ب")
    # Every adjacent pair, which decides the medial and final forms.
    for first in LETTERS:
        for second in LETTERS:
            cases.append(first + second)
    # Every letter with a following harakat.
    for letter in LETTERS:
        for mark in HARAKAT:
            cases.append(letter + mark)
            cases.append("ب" + letter + mark + "ب")
    # Words and phrases.
    cases.extend(WORDS)
    return cases


EXAMPLE = '''//! Generated by research/tools/verify_arabic.py. Do not edit.
use std::io::{self, Read};
use arabic::{Direction, Language, Options, reshape_with};

fn main() {
    let language = match std::env::args().nth(1).as_deref() {
        Some("ArabicV2") => Language::ArabicV2,
        Some("Kurdish") => Language::Kurdish,
        _ => Language::Arabic,
    };
    let options = Options {
        language,
        ..Options::default()
    };
    let mut input = String::new();
    io::stdin().read_to_string(&mut input).unwrap();
    for line in input.split('\\n') {
        if line.is_empty() {
            continue;
        }
        let text = unescape(line);
        println!("{}", reshape_with(&text, Direction::Logical, options));
    }
}

// The corpus is written one case per line with \\u{..} escapes, because a case
// may contain a newline-adjacent control character that would otherwise break
// the framing.
fn unescape(line: &str) -> String {
    let mut out = String::new();
    let mut chars = line.chars().peekable();
    while let Some(c) = chars.next() {
        if c == '\\\\' && chars.peek() == Some(&'u') {
            chars.next();
            let mut hex = String::new();
            if chars.peek() == Some(&'{') {
                chars.next();
                for c in chars.by_ref() {
                    if c == '}' { break; }
                    hex.push(c);
                }
            } else {
                for _ in 0..4 {
                    if let Some(c) = chars.next() { hex.push(c); }
                }
            }
            if let Ok(n) = u32::from_str_radix(&hex, 16) {
                if let Some(c) = char::from_u32(n) { out.push(c); }
            }
        } else if c == '\\\\' && chars.peek() == Some(&'n') {
            chars.next();
            out.push('\\n');
        } else {
            out.push(c);
        }
    }
    out
}
'''


def escape(text: str) -> str:
    """Writes a case as one line, escaping anything that would break framing."""
    out = []
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif ord(c) < 0x20 or ord(c) == 0x7F:
            out.append(f"\\u{{{ord(c):X}}}")
        else:
            out.append(c)
    return "".join(out)


def rust_string(text: str) -> str:
    """A Rust string literal for `text`."""
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


# The cases the committed CI fixture records, per language. CI has no Python, so
# the answer has to be baked in; this is the subset that exercises a table
# difference without the full pairwise corpus, which would be tens of thousands
# of lines.
def fixture_cases():
    cases = []
    for letter in LETTERS:
        cases.append(letter)
        cases.append("ب" + letter)
        cases.append(letter + "ب")
        cases.append("ب" + letter + "ب")
    cases.extend(WORDS)
    return cases


def emit_fixture() -> int:
    """Writes `crates/arabic/tests/languages.rs` from the reference."""
    cases = fixture_cases()
    lines = [
        "//! Shaping fixtures for the three letter tables, generated from the",
        "//! MIT-licensed `arabic-reshaper` library by",
        "//! `research/tools/verify_arabic.py --emit`. Do not edit by hand: the",
        "//! answer for each case is the reference's, so a hand edit would defeat",
        "//! the point of the fixture.",
        "",
        "use arabic::{Direction, Language, Options, reshape_with};",
        "",
    ]
    for language in LANGUAGES:
        reference = arabic_reshaper.ArabicReshaper(
            {
                "language": language,
                "delete_harakat": False,
                "delete_tatweel": False,
                "support_zwj": True,
                "support_ligatures": True,
            }
        )
        name = language.upper()
        # Arabic -> ARABIC, ArabicV2 -> ARABICV2, Kurdish -> KURDISH: keep the
        # reference's own spelling so the constant names read like the tables.
        lines.append(f"/// `{language}` cases: `(input, expected)`.")
        lines.append(f"const {name}: &[(&str, &str)] = &[")
        for text in cases:
            try:
                expected = reference.reshape(text)
            except Exception:  # noqa: BLE001 - the reference's own defect
                continue
            lines.append(f"    ({rust_string(text)}, {rust_string(expected)}),")
        lines.append("];")
        lines.append("")
    lines.extend(
        [
            "/// Every case in every table, shaped with the matching language.",
            "#[test]",
            "fn every_table_matches_the_reference_implementation() {",
            "    let tables = [",
            "        (Language::Arabic, ARABIC),",
            "        (Language::ArabicV2, ARABICV2),",
            "        (Language::Kurdish, KURDISH),",
            "    ];",
            "    for (language, cases) in tables {",
            "        let options = Options {",
            "            language,",
            "            ..Options::default()",
            "        };",
            "        for (input, expected) in cases {",
            "            let got = reshape_with(input, Direction::Logical, options);",
            "            assert_eq!(got, *expected, \"{language:?} input {input:?}\");",
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    out = ROOT / "crates" / "arabic" / "tests" / "languages.rs"
    out.write_text("\n".join(lines))
    total = sum(1 for _ in cases) * len(LANGUAGES)
    print(f"wrote {out.relative_to(ROOT)} ({total} cases)")
    print(f"reference: arabic-reshaper {arabic_reshaper.__version__}")
    return 0


def run_rust(cases, language="Arabic"):
    example = CRATE / "examples" / "_oracle_reshape.rs"
    example.parent.mkdir(exist_ok=True)
    example.write_text(EXAMPLE)
    try:
        r = subprocess.run(
            ["cargo", "run", "--quiet", "--example", "_oracle_reshape", "--", language],
            cwd=CRATE,
            input="\n".join(escape(c) for c in cases) + "\n",
            capture_output=True,
            text=True,
            env=CARGO_ENV,
        )
        if r.returncode != 0:
            raise SystemExit(r.stderr[-4000:])
        return r.stdout.split("\n")
    finally:
        example.unlink()


# The reference's `language` setting, and the same three names the crate uses.
LANGUAGES = ["Arabic", "ArabicV2", "Kurdish"]


def main() -> int:
    cases = corpus()
    failed = False
    for language in LANGUAGES:
        reference = arabic_reshaper.ArabicReshaper(
            {
                "language": language,
                "delete_harakat": False,
                "delete_tatweel": False,
                "support_zwj": True,
                "support_ligatures": True,
            }
        )
        ours = run_rust(cases, language)
        mismatches = 0
        shown = 0
        crashes = 0
        for index, text in enumerate(cases):
            mine = ours[index] if index < len(ours) else "<missing>"
            try:
                theirs = reference.reshape(text)
            except Exception:  # noqa: BLE001 - the reference's own failure
                # arabic-reshaper 3.0.0 raises IndexError on a harakat that
                # follows a letter it does not know (e.g. "آ" + "ِ"). That is a
                # defect in the reference, not a disagreement with this crate,
                # so it is counted separately instead of being reported as a
                # mismatch.
                crashes += 1
                continue
            if mine != theirs:
                mismatches += 1
                if shown < 25:
                    shown += 1
                    print(
                        f"[{language}] MISMATCH {escape(text)!r}\n"
                        f"  rust={mine!r}\n"
                        f"  ref ={theirs!r}"
                    )
        if mismatches > shown:
            print(f"[{language}] ... and {mismatches - shown} more")
        compared = len(cases) - crashes
        print(
            f"[{language}] {compared - mismatches}/{compared} reshape cases agree "
            f"with arabic-reshaper {arabic_reshaper.__version__}"
        )
        if crashes:
            print(f"[{language}] {crashes} cases skipped: the reference raises on them")
        if mismatches:
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    if "--emit" in sys.argv[1:]:
        raise SystemExit(emit_fixture())
    raise SystemExit(main())
