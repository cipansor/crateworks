# message key -> (schema URL, crate type, fixture)
CASES = {
    "pacs008": (
        f"{BASE}/pacs/schemas/pacs.008.001.08.xsd",
        "iso20022_rs::pacs::CreditTransfer",
        PACS008,
    ),
    "pain001": (
        f"{BASE}/pain/schemas/pain.001.001.09.xsd",
        "iso20022_rs::pain::CreditTransferInitiation",
        PAIN001,
    ),
}

EXAMPLE = """//! Generated by research/tools/verify_iso20022.py. Do not edit.
use %s;

fn main() {
    let xml = r#"%s"#;
    let message = %s::parse(xml).expect("parse");
    print!("{}", message.to_xml().expect("write"));
}
"""


def fetch(url: str) -> pathlib.Path:
    path = CACHE / pathlib.Path(url).name
    if path.exists():
        return path
    CACHE.mkdir(parents=True, exist_ok=True)
    print(f"downloading {url}")
    with urllib.request.urlopen(url, timeout=60) as response:
        path.write_bytes(response.read())
    return path


def generate(work: pathlib.Path, case: str) -> pathlib.Path:
    _, type_path, fixture = CASES[case]
    crate = work / case
    (crate / "src").mkdir(parents=True, exist_ok=True)
    crate_path = ROOT / "crates" / "iso20022-rs"
    manifest = (
        "[package]\n"
        'name = "iso-gen"\n'
        'version = "0.0.0"\n'
        'edition = "2024"\n'
        "\n[dependencies]\n"
        f'iso20022-rs = {{ path = "{crate_path}" }}\n'
        "\n[workspace]\n"
    )
    (crate / "Cargo.toml").write_text(manifest)
    (crate / "src" / "main.rs").write_text(EXAMPLE % (type_path, fixture, type_path))
    out = work / f"{case}.xml"
    result = subprocess.run(
        ["cargo", "run", "-q"], cwd=crate, env=CARGO_ENV, capture_output=True, text=True
    )
    if result.returncode != 0:
        sys.exit(f"{case}: the crate failed to build or run:\n{result.stderr}")
    out.write_text(result.stdout)
    return out


def main() -> int:
    try:
        import xmlschema
    except ImportError:
        sys.exit("this needs an XSD engine: pip install xmlschema")

    cases = sys.argv[1:] or list(CASES)
    unknown = [c for c in cases if c not in CASES]
    if unknown:
        sys.exit(f"unknown case(s) {unknown}; choose from {list(CASES)}")

    work = CACHE / "iso20022"
    work.mkdir(parents=True, exist_ok=True)
    failed = False
    for case in cases:
        url, _, _ = CASES[case]
        out = generate(work, case)
        schema = xmlschema.XMLSchema(str(fetch(url)))
        errors = list(schema.iter_errors(str(out)))
        if errors:
            failed = True
            print(f"INVALID: {case} has {len(errors)} schema error(s)")
            for error in errors[:20]:
                print(f"  - {error.reason} | {error.path}")
        else:
            print(f"VALID: generated {case} conforms to the official ISO 20022 XSD")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
