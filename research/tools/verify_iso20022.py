#!/usr/bin/env python3
"""Regression gate for the ISO 20022 writers in `crates/iso20022-rs`.

`iso20022-rs` builds payment messages from its own model, and a message a bank
rejects is worse than no message at all. The authority on what a bank accepts is
the official ISO 20022 XML schema, so this script generates each message with
the crate and validates it against the schema for that message version.

The schemas are downloaded once and cached under `.cache/`. Validation needs a
real XSD engine; the standard library's `xml.etree` does not implement schema
validation, so this needs `pip install xmlschema`.

Run:  python3 research/tools/verify_iso20022.py [pacs008 pain001 ...]
Needs: pip install xmlschema
"""

