#!/usr/bin/env python3
"""Regression gate for the localized names in `crates/hijridate`.

The `hijridate` Python package publishes the Hijri and Gregorian month names,
the day names and the era notations in four languages. This crate transcribes
those tables, and a transcription slip is easy and silent, so every string is
compared against the reference. It exits non-zero on any difference.

Run:  python3 research/tools/verify_hijri_locales.py
Needs: pip install hijridate
"""

import os
import pathlib
import subprocess
import sys

import hijridate
from hijridate import locales

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRATE = ROOT / "crates" / "hijridate"
CARGO_ENV = {
    **os.environ,
    "PATH": "/workspace/.toolchain/cargo/bin:" + os.environ.get("PATH", ""),
    "CARGO_HOME": "/workspace/.toolchain/cargo",
}

# crate `Language` variant -> reference locale class.
LANGUAGES = {
    "English": locales.EnglishLocale,
    "Arabic": locales.ArabicLocale,
    "Bengali": locales.BengaliLocale,
    "Turkish": locales.TurkishLocale,
}

EXAMPLE = """//! Generated by research/tools/verify_hijri_locales.py. Do not edit.
use hijridate::Language;

fn main() {
    for (name, language) in __LANGUAGES__ {
        for (index, value) in language.hijri_month_names().iter().enumerate() {
            println!("{name}\\thijri_month\\t{index}\\t{value}");
        }
        for (index, value) in language.gregorian_month_names().iter().enumerate() {
            println!("{name}\\tgregorian_month\\t{index}\\t{value}");
        }
        for (index, value) in language.day_names().iter().enumerate() {
            println!("{name}\\tday\\t{index}\\t{value}");
        }
        println!("{name}\\thijri_notation\\t0\\t{}", language.hijri_notation());
        println!(
            "{name}\\tgregorian_notation\\t0\\t{}",
            language.gregorian_notation()
        );
    }
}
"""


def run_rust():
    cases = "\n".join(
        f'        ("{name}", Language::{name}),' for name in LANGUAGES
    )
    example = CRATE / "examples" / "_oracle_locales.rs"
    example.parent.mkdir(exist_ok=True)
    example.write_text(EXAMPLE.replace("__LANGUAGES__", f"[\n{cases}\n    ]"))
    try:
        r = subprocess.run(
            ["cargo", "run", "--quiet", "--example", "_oracle_locales"],
            cwd=CRATE, capture_output=True, text=True, env=CARGO_ENV,
        )
        if r.returncode != 0:
            raise SystemExit(r.stderr[-4000:])
        out = {}
        for line in r.stdout.splitlines():
            if not line.strip():
                continue
            name, kind, index, value = line.split("\t", 3)
            out[(name, kind, int(index))] = value
        return out
    finally:
        example.unlink()


def expected():
    out = {}
    for name, cls in LANGUAGES.items():
        for index, value in enumerate(cls.month_names):
            out[(name, "hijri_month", index)] = value
        for index, value in enumerate(cls.gregorian_month_names):
            out[(name, "gregorian_month", index)] = value
        for index, value in enumerate(cls.day_names):
            out[(name, "day", index)] = value
        out[(name, "hijri_notation", 0)] = cls.notation
        out[(name, "gregorian_notation", 0)] = cls.gregorian_notation
    return out


def main() -> int:
    ours = run_rust()
    theirs = expected()
    mismatches = 0
    for key in sorted(theirs):
        mine = ours.get(key)
        if mine != theirs[key]:
            mismatches += 1
            print(f"MISMATCH {key}\n  rust={mine!r}\n  ref ={theirs[key]!r}")
    for key in sorted(set(ours) - set(theirs)):
        mismatches += 1
        print(f"EXTRA    {key} rust={ours[key]!r}")
    print(f"\n{len(theirs) - mismatches}/{len(theirs)} names agree with hijridate")
    return 1 if mismatches else 0


if __name__ == "__main__":
    raise SystemExit(main())
