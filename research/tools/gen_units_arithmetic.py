#!/usr/bin/env python3
"""Regenerate `crates/runits/tests/fixtures/pint_arithmetic.tsv`.

`verify_units.py` checks a single unit's scale against pint. It cannot check
arithmetic, because a sum has an output and not just a scale. This script is the
oracle for `Quantity::add` and `Quantity::subtract`: it asks pint to add two
quantities and records the number it returns in the left operand's unit, which
is the unit pint keeps.

Every line is `<left>\t<right>\t<expected>`, where `left` and `right` are
quantities written as text (`"3.5 kg"`) and `expected` is pint's result in the
left unit, or `-` when pint raises (a sum across two dimensions, or either
operand an affine scale).

Inputs are generated deterministically: quantities are drawn from the units the
crate already supports, paired within a dimension, with magnitudes spanning
several decades. A separate slice pairs units of different dimensions, where the
only correct answer is an error.

Run from the repository root:

    python3 research/tools/gen_units_arithmetic.py

It rewrites the fixture in place. Needs `pip install pint`.
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import pint

ROOT = Path(__file__).resolve().parent.parent.parent
FIXTURE = ROOT / "crates" / "runits" / "tests" / "fixtures" / "pint_arithmetic.tsv"

# The reference's units, keyed by the seven SI base dimensions. Only the names
# the crate resolves are used, so a missing fixture row is a crate gap rather
# than an unknown unit. Affine scales (degC, degF) are excluded on purpose: a
# sum of them has no meaning, and pint refuses it, so they belong to the error
# slice instead.
BY_DIMENSION: dict[tuple[int, ...], list[str]] = {
    (1, 0, 0, 0, 0, 0, 0): ["m", "km", "cm", "mm", "ft", "in", "mi", "yard", "nmi"],
    (0, 0, 1, 0, 0, 0, 0): ["g", "kg", "mg", "lb", "oz", "tonne", "stone"],
    (0, 1, 0, 0, 0, 0, 0): ["s", "ms", "min", "h", "day", "week", "year"],
    (3, 0, 0, 0, 0, 0, 0): ["L", "mL", "m^3", "gal", "quart", "pint", "cup"],
    (0, 0, 0, 0, 0, 0, 0): ["radian", "degree", "gradian", "turn"],
    (1, -1, 0, 0, 0, 0, 0): ["m/s", "km/h", "mph", "knot"],
    (1, -2, 1, 0, 0, 0, 0): ["N", "kg*m/s^2", "dyn", "lbf"],
    (2, -2, 1, 0, 0, 0, 0): ["J", "kWh", "cal", "erg", "BTU"],
    (2, -3, 1, 0, 0, 0, 0): ["W", "kW", "hp", "MW"],
}

# Units from different dimensions, so every pair is a dimension mismatch.
MISMATCH = ["m", "kg", "s", "L", "radian", "N", "J", "W"]

# Magnitudes spanning micro to mega, so a factor bug shows up at both ends.
MAGNITUDES = [
    1e-6, 1e-3, 0.1, 0.5, 1.0, 2.5, 7.0, 12.0, 99.0, 1e3, 1e6,
]


def quantity(value: float, unit: str) -> str:
    return f"{value!r} {unit}"


def main() -> int:
    registry = pint.UnitRegistry()
    rng = random.Random(20261027)
    rows: list[tuple[str, str, str]] = []

    for names in BY_DIMENSION.values():
        for _ in range(120):
            left_unit, right_unit = rng.choice(names), rng.choice(names)
            left = quantity(rng.choice(MAGNITUDES), left_unit)
            right = quantity(rng.choice(MAGNITUDES), right_unit)
            left_q = registry.Quantity(left)
            right_q = registry.Quantity(right)
            try:
                result = left_q + right_q
            except Exception:
                expected = "-"
            else:
                expected = repr(float(result.magnitude))
            rows.append((left, right, expected))

    # The error slice: a different dimension on each side, and the affine
    # scales that pint refuses to add.
    for _ in range(120):
        left = quantity(rng.choice(MAGNITUDES), rng.choice(MISMATCH))
        right = quantity(rng.choice(MAGNITUDES), rng.choice(MISMATCH))
        left_q = registry.Quantity(left)
        right_q = registry.Quantity(right)
        try:
            left_q + right_q
        except Exception:
            expected = "-"
        else:
            expected = repr(float((left_q + right_q).magnitude))
        rows.append((left, right, expected))

    for affine in ["degC", "degF", "K"]:
        for other in ["degC", "degF", "K"]:
            left = quantity(20.0, affine)
            right = quantity(5.0, other)
            try:
                result = registry.Quantity(left) + registry.Quantity(right)
            except Exception:
                expected = "-"
            else:
                expected = repr(float(result.magnitude))
            rows.append((left, right, expected))

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    with FIXTURE.open("w", encoding="utf-8") as handle:
        handle.write("# Generated by research/tools/gen_units_arithmetic.py from pint - do not edit.\n")
        handle.write("# left\tright\texpected (left unit), '-' when pint raises\n")
        for left, right, expected in rows:
            handle.write(f"{left}\t{right}\t{expected}\n")

    errors = sum(1 for _, _, expected in rows if expected == "-")
    print(f"wrote {len(rows)} rows to {FIXTURE.relative_to(ROOT)} ({errors} expected errors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
